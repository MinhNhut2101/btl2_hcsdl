CREATE TABLE dbo.CHAM_CONG (
 MaNV VARCHAR(30) NOT NULL, MaCa VARCHAR(30) NOT NULL,
 TrangThaiCong VARCHAR(30) NOT NULL,
 TrangThaiDuyet VARCHAR(20) NOT NULL CONSTRAINT DF_CC_Duyet DEFAULT 'ChoDuyet',
 HinhThuc VARCHAR(20) NOT NULL CONSTRAINT DF_CC_HinhThuc DEFAULT 'ThuCong',
 PhutCongDuyet INT NULL,
 LaNgoaiLeCong BIT NOT NULL CONSTRAINT DF_CC_NgoaiLe DEFAULT 0,
 PhutTangCaDuyet INT NOT NULL CONSTRAINT DF_CC_OT DEFAULT 0,
 LoaiNgayTangCa VARCHAR(20) NULL, ThoiDiemDuyet DATETIME2(0) NULL,
 GhiChu NVARCHAR(1000) NULL, CanCuDuyetCong NVARCHAR(1000) NULL,
 GioVaoThucTe DATETIME2(0) NULL, GioRaThucTe DATETIME2(0) NULL,
 OTTruocBatDau DATETIME2(0) NULL, OTTruocKetThuc DATETIME2(0) NULL,
 OTSauBatDau DATETIME2(0) NULL, OTSauKetThuc DATETIME2(0) NULL,
 MaNVDuyet VARCHAR(30) NULL,
 CONSTRAINT PK_CHAM_CONG PRIMARY KEY(MaNV,MaCa),
 CONSTRAINT FK_CC_LV FOREIGN KEY(MaNV,MaCa) REFERENCES dbo.LAM_VIEC(MaNV,MaCa),
 CONSTRAINT FK_CC_Duyet FOREIGN KEY(MaNVDuyet) REFERENCES dbo.QUAN_LY(MaNV),
 CONSTRAINT CK_CC_TrangThaiCong CHECK(TrangThaiCong IN
   ('DiLam','NghiPhepHuongLuong','NghiPhepKhongLuong','NghiKhongPhep')),
 CONSTRAINT CK_CC_HinhThuc CHECK(HinhThuc IN ('ThuCong','ChamCongDienTu')),
 CONSTRAINT CK_CC_Phut CHECK((PhutCongDuyet IS NULL OR PhutCongDuyet>=0) AND PhutTangCaDuyet>=0),
 CONSTRAINT CK_CC_TrangThaiDuyet CHECK(
   (TrangThaiDuyet='ChoDuyet' AND MaNVDuyet IS NULL AND ThoiDiemDuyet IS NULL
       AND PhutCongDuyet IS NULL AND PhutTangCaDuyet=0 AND LoaiNgayTangCa IS NULL AND LaNgoaiLeCong=0)
   OR (TrangThaiDuyet='DaDuyet' AND MaNVDuyet IS NOT NULL AND ThoiDiemDuyet IS NOT NULL
       AND PhutCongDuyet IS NOT NULL AND CanCuDuyetCong IS NOT NULL
       AND LEN(LTRIM(RTRIM(CanCuDuyetCong)))>0)),
 CONSTRAINT CK_CC_NgoaiLe CHECK(LaNgoaiLeCong=0 OR (TrangThaiCong='DiLam' AND TrangThaiDuyet='DaDuyet')),
 CONSTRAINT CK_CC_LoaiNgayOT CHECK(
   (PhutTangCaDuyet=0 AND LoaiNgayTangCa IS NULL)
   OR (PhutTangCaDuyet>0 AND LoaiNgayTangCa IS NOT NULL AND LoaiNgayTangCa IN ('NgayThuong','NgayNghiTuan','NgayLe'))),
 CONSTRAINT CK_CC_GioRa CHECK(GioRaThucTe IS NULL OR (GioVaoThucTe IS NOT NULL AND GioRaThucTe>GioVaoThucTe)),
 CONSTRAINT CK_CC_OTTruoc CHECK((OTTruocBatDau IS NULL AND OTTruocKetThuc IS NULL)
   OR (OTTruocBatDau IS NOT NULL AND OTTruocKetThuc IS NOT NULL AND OTTruocBatDau<OTTruocKetThuc)),
 CONSTRAINT CK_CC_OTSau CHECK((OTSauBatDau IS NULL AND OTSauKetThuc IS NULL)
   OR (OTSauBatDau IS NOT NULL AND OTSauKetThuc IS NOT NULL AND OTSauBatDau<OTSauKetThuc)),
 CONSTRAINT CK_CC_NghiCa CHECK(TrangThaiCong='DiLam' OR
   (GioVaoThucTe IS NULL AND GioRaThucTe IS NULL AND OTTruocBatDau IS NULL
    AND OTSauBatDau IS NULL AND PhutTangCaDuyet=0 AND (PhutCongDuyet IS NULL OR PhutCongDuyet=0)))
