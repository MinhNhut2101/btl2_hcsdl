CREATE TABLE dbo.NHAN_VIEN (
 MaNV VARCHAR(30) NOT NULL CONSTRAINT PK_NHAN_VIEN PRIMARY KEY,
 HoTen NVARCHAR(150) NOT NULL,
 TrangThaiLamViec VARCHAR(20) NOT NULL CONSTRAINT DF_NV_TrangThai DEFAULT 'DangLam',
