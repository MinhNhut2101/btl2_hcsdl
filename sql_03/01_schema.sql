 TenNganHang NVARCHAR(150) NULL, SoTaiKhoan VARCHAR(50) NULL,
 ChuTaiKhoan NVARCHAR(150) NULL, SoGiayToTuyThan VARCHAR(30) NULL,
 DuocLapPhieuKho BIT NOT NULL CONSTRAINT DF_NV_LapKho DEFAULT 0,
 CONSTRAINT CK_NV_Ten CHECK (LEN(LTRIM(RTRIM(HoTen)))>0),
 CONSTRAINT CK_NV_TrangThai CHECK (TrangThaiLamViec IN ('DangLam','DaNghi')),
 CONSTRAINT CK_NV_NgayNghi CHECK (
   (TrangThaiLamViec='DangLam' AND NgayNghiViec IS NULL)
   OR (TrangThaiLamViec='DaNghi' AND NgayNghiViec IS NOT NULL AND NgayNghiViec>=NgayVaoLam)),
 CONSTRAINT CK_NV_TaiKhoan CHECK (
   (TenNganHang IS NULL AND SoTaiKhoan IS NULL AND ChuTaiKhoan IS NULL)
   OR (TenNganHang IS NOT NULL AND SoTaiKhoan IS NOT NULL AND ChuTaiKhoan IS NOT NULL
       AND LEN(LTRIM(RTRIM(TenNganHang)))>0 AND LEN(LTRIM(RTRIM(SoTaiKhoan)))>0
       AND LEN(LTRIM(RTRIM(ChuTaiKhoan)))>0))
);
CREATE UNIQUE INDEX UX_NV_GiayTo ON dbo.NHAN_VIEN(SoGiayToTuyThan)
 WHERE SoGiayToTuyThan IS NOT NULL;
