 DiaChiChiTiet NVARCHAR(255) NULL, DiaChiTinhThanh NVARCHAR(100) NULL,
 DiaChiQuanHuyen NVARCHAR(100) NULL, DiaChiPhuongXa NVARCHAR(100) NULL,
